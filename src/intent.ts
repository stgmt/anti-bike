/**
 * Ступень 1: обещает ли текст завести новую сущность. Без модели, без сети.
 *
 * Это отсев, а не решение. Его работа — не пустить к модели те ходы, где писать
 * нечего. Ложный пропуск тут дешевле ложного срабатывания: ход уйдёт в модель
 * и получит «нет».
 *
 * Почему глагол плюс существительное, а не слово «велосипед»: на замерах вопрос
 * «это велосипед?» дал обратный ответ, а поиск обещания сущности — верный.
 *
 * Формы глаголов заданы регулярками, а не основами: первый прогон показал, что
 * основа «введ» не ловит «ввести» и «ввожу». Русская морфология тут важна —
 * без неё ступень 1 пропускает ровно те ходы, ради которых сделана.
 */

/**
 * Глаголы, которыми агент объявляет, что сейчас что-то заведёт.
 *
 * Формы: инфинитив, первое лицо будущего и настоящего времени. Прошедшее время
 * («сделал», «ввёл») сюда не входит: это отчёт о готовом, а не обещание.
 */
const VERB_PATTERN =
  /(введ(у|ём|ем|ёт|ет)?|ввести|введу|ввожу|вводить|добав(лю|ит|ить|ляю)|созда(м|ю|ть|ёт)|предлаг(аю|ать)|предложу|завест[иь]|заведу|напиш[уе]|написать|реализу(ю|ем|й)?|вынес(у|ти)?|собер(у|ём)?|собрать|определ(ю|ить)|постро(ю|ить)|сдела(ю|ть|ем))/i;

/**
 * Сущности, которые означают новый код в проекте.
 *
 * Список узкий нарочно: широкие слова («модель», «тест», «шаг») есть почти в каждом
 * отчёте, и ступень 1 перестала бы отсеивать.
 */
const NOUN_PATTERN =
  /(класс|объект|датакласс|dataclass|слой|прослойк|обёртк|обертк|абстракци|контейнер|адаптер|менеджер|раннер|сервис|модул|хелпер|утилит|переключател|хук|скрипт|обработчик|валидатор|чекер|порт[ауы]?\b)/i;

export interface Intent {
  /** Есть ли в тексте обещание завести новую сущность. */
  promise: boolean;
  /** Что именно нашлось: нужно для сообщения и для замеров. */
  matches: string[];
}

/**
 * Ищет в тексте обещание новой сущности.
 *
 * Условие — глагол и существительное в пределах одного предложения.
 * Пара через всё сообщение даёт ложные срабатывания: отчёт «я сделал X» и
 * отдельно «модуль Y уже есть» не обещают новую сущность.
 */
export function detectIntent(text: string): Intent {
  const matches: string[] = [];
  // Предложения режем по точке, восклицательному, вопросительному и переводу строки.
  for (const sentence of text.split(/(?<=[.!?])\s+|\n+/)) {
    const verb = VERB_PATTERN.exec(sentence);
    if (!verb) continue;
    const noun = NOUN_PATTERN.exec(sentence);
    if (!noun) continue;
    matches.push(`${verb[0].toLowerCase()}…${noun[0].toLowerCase()}`);
  }
  return { promise: matches.length > 0, matches };
}
